/**
 * build-sprites.ts
 *
 * Writes each country package's dist/sprite.svg and dist/sprite.css from the
 * artwork already inlined in its generated registry.
 *
 * This runs as part of `yarn compile` (and therefore as part of the release
 * workflow) precisely because it needs no network and no assets/ directory.
 * The previous implementation lived in create-assets.ts, which only runs
 * during a full `yarn update` scrape — so the sprites were never rebuilt on
 * CI and the published packages shipped neither them nor the assets/ tree
 * their CSS referenced.
 *
 * Both artefacts are self-contained:
 *   sprite.svg  — a <symbol> sheet, one symbol per sign, referenced with
 *                 <use href="…/sprite.svg#rs-{cc}-{signId}">.
 *   sprite.css  — one class per sign, artwork embedded as a data URI, so a
 *                 plain <link> is enough with no other files to copy.
 *
 * Usage:  yarn build-sprites [--country=us]
 */

import fs from 'fs';
import path from 'path';
import { PACKAGES_DIR, listCountries, readRegistry } from './lib/registry';
import type { RegistrySign } from './lib/registry';

/** Fallback canvas for artwork that declares no viewBox. */
const DEFAULT_VIEWBOX = '0 0 100 100';

/** Split an inline SVG into its viewBox and its inner markup. */
const splitSvg = (svg: string): { viewBox: string; inner: string } | null => {
  const m = svg.match(/^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  if (!m) return null;
  const viewBox = m[1].match(/\bviewBox=["']([^"']+)["']/)?.[1] ?? DEFAULT_VIEWBOX;
  return { viewBox, inner: m[2] };
};

/**
 * Encode an SVG for use inside `url("…")`.
 *
 * Percent-encoding only the characters that actually terminate a CSS url()
 * or an XML data URI keeps this ~35% smaller than base64, and it gzips far
 * better because the markup stays readable text.
 */
const svgDataUri = (svg: string): string =>
  `data:image/svg+xml,${svg
    .replace(/\s+/g, ' ')
    .replace(/"/g, "'")
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .trim()}`;

const className = (cc: string, id: string): string => `rs-${cc}-${id}`;

const buildSpriteSvg = (cc: string, signs: RegistrySign[]): { svg: string; count: number } => {
  const symbols: string[] = [];
  for (const sign of signs) {
    const symbolId = className(cc, sign.id);
    if (sign.svg) {
      const parts = splitSvg(sign.svg);
      if (!parts) continue;
      symbols.push(`<symbol id="${symbolId}" viewBox="${parts.viewBox}">${parts.inner}</symbol>`);
    } else if (sign.png) {
      // Raster-only sign: wrap the data URI so it is addressable the same way.
      symbols.push(
        `<symbol id="${symbolId}" viewBox="0 0 240 240">` +
          `<image href="${sign.png}" width="240" height="240"/></symbol>`,
      );
    }
  }
  const svg = [
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none">`,
    `<!-- Road signs — ${cc.toUpperCase()} — SVG symbol sheet. Generated by 'yarn build-sprites'. Do not edit. -->`,
    ...symbols,
    `</svg>`,
    ``,
  ].join('\n');
  return { svg, count: symbols.length };
};

const buildSpriteCss = (cc: string, signs: RegistrySign[]): { css: string; count: number } => {
  const lines = [
    `/* Road signs — ${cc.toUpperCase()} — CSS sprite.`,
    `   Generated by 'yarn build-sprites'. Do not edit manually.`,
    ``,
    `   Every class embeds its own artwork as a data URI, so this stylesheet is`,
    `   self-contained — no image files to copy alongside it. Give the element a`,
    `   size; the artwork scales to fit.`,
    ``,
    `     <span class="rs-${cc}-<sign-id>" style="display:inline-block;width:64px;height:64px"`,
    `           role="img" aria-label="…"></span> */`,
    ``,
  ];
  let count = 0;
  for (const sign of signs) {
    const uri = sign.svg ? svgDataUri(sign.svg) : sign.png;
    if (!uri) continue;
    lines.push(
      `.${className(cc, sign.id)} {`,
      `  background-image: url("${uri}");`,
      `  background-position: center;`,
      `  background-repeat: no-repeat;`,
      `  background-size: contain;`,
      `}`,
      ``,
    );
    count++;
  }
  return { css: lines.join('\n'), count };
};

const mb = (n: number): string => `${(n / 1024 / 1024).toFixed(1)}MB`;

const main = (): void => {
  const only = process.argv.find((a) => a.startsWith('--country='))?.split('=')[1];
  const countries = only ? [only] : listCountries();

  let built = 0;
  let skipped = 0;
  let totalBytes = 0;

  for (const cc of countries) {
    const signs = readRegistry(cc);
    if (signs.length === 0) {
      skipped++;
      continue;
    }
    const distDir = path.join(PACKAGES_DIR, cc, 'dist');
    fs.mkdirSync(distDir, { recursive: true });

    const { svg, count: symbolCount } = buildSpriteSvg(cc, signs);
    const { css, count: classCount } = buildSpriteCss(cc, signs);
    fs.writeFileSync(path.join(distDir, 'sprite.svg'), svg, 'utf-8');
    fs.writeFileSync(path.join(distDir, 'sprite.css'), css, 'utf-8');

    totalBytes += Buffer.byteLength(svg) + Buffer.byteLength(css);
    built++;
    if (only) {
      console.log(`  ${cc}: ${symbolCount} symbols, ${classCount} classes`);
    }
  }

  console.log(
    `Built sprites for ${built} countries (${mb(totalBytes)} total)` +
      (skipped ? `; skipped ${skipped} with an empty registry` : ''),
  );
};

main();
