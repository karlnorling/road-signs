export interface SignAssets {
  jpg: Record<number, string>;
  png: Record<number, string>;
  /** Relative path to the SVG source file. Absent for PDF-extracted (PNG-only) signs. */
  svg?: string;
  webp: Record<number, string>;
}

/**
 * A single road sign. TCategory is narrowed per country package
 * (e.g. USCategory = 'warning' | 'regulatory' | ...).
 *
 * Every sign carries its own artwork inline — `svg` for vector signs, `png`
 * (a base64 data URI) for the handful of PDF-extracted signs that have no
 * vector source. Rendering a sign never requires a file outside the package.
 */
export interface Sign<TCategory extends string = string> {
  /**
   * Paths to the generated raster/vector files in the monorepo's
   * `packages/@road-signs/{cc}/assets/` tree.
   *
   * These are **build-time paths and are not part of the published package** —
   * the assets directory is ~16GB across all countries and is regenerated by
   * `yarn update`. Use `svg` or `png` for rendering; use this only when working
   * inside the repo, where the files exist on disk.
   */
  assets?: SignAssets;
  category: TCategory;
  /** Official sign code, e.g. "W1-1" (US), "670" (UK). */
  code: string;
  description: string;
  /** Slug ID, e.g. "w1-1-turn". Unique within a country package. */
  id: string;
  name: string;
  /**
   * Base64 PNG data URI. Present only for PDF-extracted signs that have no
   * vector source, so that `svg` and `png` are never both absent.
   */
  png?: string;
  /** Inline SVG string, SVGO-optimised. Absent for PDF-extracted (PNG-only) signs. */
  svg?: string;
}

/**
 * Standard five-category taxonomy shared by Vienna Convention countries.
 * Used by: AT, BE, CH, CZ, DE, DK, ES, FI, FR, GR, HR, HU, IE, IS, IT,
 *           LI, LT, LV, ME, MT, NL, NO, PL, PT, RO, RS, SE, SI, SK, TR…
 */
export type ViennaCategory = 'information' | 'mandatory' | 'priority' | 'prohibitory' | 'warning';

export type ViennaSign = Sign<ViennaCategory>;
